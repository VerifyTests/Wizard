    static void AppendRunning(MarkdownBuilder builder, Plan plan)
    {
        builder.Heading(2, "Running the tests");
        builder.Paragraph("From the solution directory:");
        builder.Code(Plan.TestCommand);
        if (plan.Framework.UsesTestingPlatform)
        {
            builder.Paragraph($"The test project is also an executable, so `dotnet run --project src/{plan.TestProject}` runs the tests directly.");
        }

        if (plan.HasWindowsProject)
        {
            builder.Paragraph($"`{plan.WindowsTestProject}` targets `{WizardDefaults.TargetFramework}-windows`, because {InteractionRules.Join([.. plan.WindowsPlugins.Select(_ => _.Id)])} renders with Windows APIs. It is part of the solution, so `dotnet test` builds it on Windows and fails on other operating systems. To build only the portable projects there, name them: `dotnet test src/{plan.TestProject}`.");
        }

        AppendBeforeRunning(builder, plan);
        AppendFirstRun(builder);
    }

    static void AppendBeforeRunning(MarkdownBuilder builder, Plan plan)
    {
        var requirements = plan.Plugins
            .SelectMany(_ => _.Definition.ExternalRequirements)
            .DistinctBy(_ => _.Name)
            .ToList();
        if (requirements.Count > 0)
        {
            builder.Heading(3, "Before running");
            builder.Bullets(
                requirements.Select(
                    _ =>
                    {
                        var text = $"**{_.Name}** — {_.Description}";
                        if (_.EnvironmentVariable is { } variable)
                        {
                            text += $" Read from the environment variable `{variable}`.";
                        }

                        if (_.Url is { } url)
                        {
                            text += $" <{url}>";
                        }

                        return text;
                    }));
        }
    }

    static void AppendFirstRun(MarkdownBuilder builder)
    {
        builder.Paragraph("A new test has no `.verified.` file, so its first run fails and writes a `.received.` file. Review it, then accept it by renaming it to `.verified.`, accepting it in the diff tool, DiffEngineTray or IDE plugin, or running `dotnet verify accept`.");
        builder.Paragraph("Set the environment variable `DiffEngine_Disabled=true` when running tests where a diff tool should not open, such as a build server or an AI assistant's terminal. Verify detects the common build servers itself.");
    }

