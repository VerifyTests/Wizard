    }

    /// <summary>Include files are written for a fixed heading depth; nested under a level-3 heading they move down.</summary>
    static string DemoteHeadings(string markdown, int levels) =>
        Regex.Replace(markdown, "^(#+) ", _ => new string('#', _.Groups[1].Length + levels) + " ", RegexOptions.Multiline);

    static string StripBanner(string code) =>
        string.Join('\n', code.Split('\n').SkipWhile(_ => _.StartsWith("//") || _.Length == 0)).TrimEnd();
}
