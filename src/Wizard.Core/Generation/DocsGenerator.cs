    static void AppendBuildServer(MarkdownBuilder builder, Plan plan)
    {
        if (BuildServerFiles.For(plan) is not { } file)
        {
            return;
        }

        builder.Heading(2, $"Getting .received in output on {plan.BuildServer.Name()}");
        var include = plan.BuildServer switch
        {
            BuildServer.GitHubActions => "build-server-githubactions",
            BuildServer.AzureDevOps => "build-server-azuredevops",
            _ => "build-server-appveyor"
        };
        builder.Raw(ContentFiles.Include(include));
        builder.Paragraph($"The solution's `{file.Path}` builds, runs the tests, and includes this step.");
    }

