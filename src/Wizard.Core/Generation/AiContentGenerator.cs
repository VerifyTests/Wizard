namespace Wizard.Core;

/// <summary>
/// Instructions for an AI coding assistant (plan 12.6): the AI tab and download, and the zip's
/// CLAUDE.md and .github/copilot-instructions.md. Project facts come first, then Verify's context-file
/// template from docs/ai-usage.md. The template's inline snapshot sections are dropped: inline
/// snapshots are still beta and the wizard does not enable them.
/// </summary>
public static class AiContentGenerator
{
    public static string Build(Plan plan)
    {
        var builder = new MarkdownBuilder();
        builder.Heading(1, $"{plan.SolutionName}: instructions for AI coding assistants");
        builder.Paragraph($"Generated by the [Verify wizard]({plan.WizardUrl}). This project was set up with Verify snapshot testing; the facts below describe that setup.");

        builder.Heading(2, "Project facts");
        builder.Bullets(
        [
            $"Solution: `{plan.SolutionName}.slnx`. Code under test is in `src/{plan.LibraryProject}`, tests in `src/{plan.TestProject}`.",
            $"Test framework: {plan.Framework.Framework.Name()}{LanguageNote(plan)}.",
            $"Run the tests from the solution directory with `{Plan.TestCommand}`.{RunnerNote(plan)}",
            $"Target framework `{WizardDefaults.TargetFramework}`, SDK pinned by `global.json` ({WizardDefaults.SdkVersion}).",
            "Packages use Central Package Management: add or change versions in `Directory.Packages.props`, and reference packages without a version.",
            $"Verify packages: {string.Join(", ", plan.TestPackages.Where(_ => _.StartsWith("Verify", StringComparison.Ordinal)).Select(_ => $"{_} {plan.Version(_)}"))}.",
            InitializationFact(plan),
            $"The Open Source Maintenance Fee declaration is in `Directory.Build.props` ({SponsorRules.Summary(plan.State)}). Do not remove it: without it every build fails with SC021."
        ]);

        AppendExtensions(builder, plan);
        builder.Raw(ContentFiles.Raw("context.md"));

        builder.Heading(2, "Environment");
        builder.Bullets(
        [
            "Set `DiffEngine_Disabled=true` when running tests, so no diff tool opens for each failed snapshot. The exception message still carries the file paths and the content.",
            "When asked to change code that has Verify tests, run the tests first: the `.received.*` files show exactly what changed.",
            "A new test fails on its first run because it has no `.verified.*` file yet. Review the `.received.*` file, then accept it by copying it to the `Verified:` path from the exception message."
        ]);
        return builder.ToString();
    }

    /// <summary>
    /// The extension cheat sheet (plan 12.6 §6): what each one is enabled by, what it puts in a
    /// snapshot, and the decisions the interaction rules took, as instructions rather than as prose.
    /// </summary>
    static void AppendExtensions(MarkdownBuilder builder, Plan plan)
    {
        if (plan.Extensions.Count == 0)
        {
            return;
        }

        builder.Heading(2, "Verify extensions in this project");
        foreach (var extension in plan.Extensions)
        {
            var definition = extension.Definition;
            builder.Heading(3, definition.DisplayName);
            var facts = new List<string>
            {
                definition.Description,
                $"Repository: {definition.RepoUrl}"
            };
            if (extension.Statements.Count > 0)
            {
                facts.Add($"Enabled in `ModuleInitializer.cs` by `{string.Join(" ", extension.Statements.Select(_ => _.Code))}`. Do not move that call after `VerifierSettings.InitializePlugins()`.");
            }

            if (extension.Samples.Count > 0)
            {
                facts.Add($"Samples: `Extensions/{extension.TestClass}.cs`, using {string.Join(", ", extension.Samples.Select(_ => $"`{_.Name}`"))}.");
            }

            if (definition.Usings.Count > 0)
            {
                facts.Add($"Needs {string.Join(", ", definition.Usings.Select(_ => $"`using {_};`"))} in the test file, not in global usings: extensions define colliding type names.");
            }

            facts.AddRange(definition.Notes);
            builder.Bullets(facts);
        }

        if (plan.Interactions.Count == 0)
        {
            return;
        }

        builder.Heading(2, "Decisions already taken");
        builder.Paragraph("These follow from the combination of extensions. Changing one of them changes behaviour across the whole test project.");
        builder.Bullets(plan.Interactions.Select(Instruction));
    }

    static string Instruction(InteractionResult interaction)
    {
        var text = $"**{string.Join(", ", interaction.Involved)}**: {interaction.Message}";
        if (interaction.Choice is { } choice &&
            choice.Options.FirstOrDefault(_ => _.Value == interaction.ChosenValue) is { } chosen)
        {
            return $"{text} In force: {chosen.Label}.";
        }

        return text;
    }

    /// <summary>The Verify skill file (plan 12.6), for .claude/skills/verify-snapshot-testing/SKILL.md.</summary>
    public static string Skill() =>
        ContentFiles.Raw("skill.md");

    static string LanguageNote(Plan plan)
    {
        if (plan.Framework.IsFSharp)
        {
            return " (tests in F#, code under test in C#)";
        }

        return "";
    }

    static string RunnerNote(Plan plan)
    {
        if (plan.Framework.UsesTestingPlatform)
        {
            return " The test project runs on Microsoft.Testing.Platform (`global.json` sets the runner), so `dotnet run --project` on it also works.";
        }

        return " Fixie runs on VSTest, which is why `global.json` does not select the Microsoft.Testing.Platform runner.";
    }

    static string InitializationFact(Plan plan)
    {
        if (plan.Framework.IsFSharp)
        {
            return "Verify is configured by the lazy `initialize` value in `Tests.fs`; every test forces it before verifying.";
        }

        return "Verify is configured in `ModuleInitializer.cs` in the test project. Explicit plugin `Initialize` calls go before `VerifierSettings.InitializePlugins()`.";
    }
}
